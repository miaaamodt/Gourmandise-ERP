import { PGlite } from '@electric-sql/pglite';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const db=new PGlite();
await db.exec('create role anon; create role authenticated;');
await db.exec(readFileSync(new URL('supabase/migrations/202611180002_shared_testing.sql',import.meta.url),'utf8'));
await db.exec('set role anon');
const sample={items:[{id:0,name:'Bread'}],tx:[],sales:[],orders:[]};
const save=(value,version)=>db.query('select public.erp_preview_save($1::jsonb,$2::bigint) result',[JSON.stringify(value),version]);
assert.equal((await db.query('select * from public.erp_preview_state')).rows[0].data,null);
await assert.rejects(db.exec("update public.erp_preview_state set version=9"),/permission denied/);
await assert.rejects(save({},0),/Invalid bakery testing data/);
assert.equal((await save(sample,0)).rows[0].result.version,1);
await assert.rejects(save(sample,0),/ERP_CONFLICT/);
const updated={...sample,tx:[{item:0,type:'prod',qty:5}]};
assert.equal((await save(updated,1)).rows[0].result.version,2);
assert.equal((await db.query('select data from public.erp_preview_state')).rows[0].data.tx[0].qty,5);
await db.exec('reset role;set role authenticated');
assert.equal((await db.query('select version from public.erp_preview_state')).rows[0].version,2);
await assert.rejects(db.exec('delete from public.erp_preview_state'),/permission denied/);
await db.close();
console.log('Public shared testing database: anonymous read/save, version conflicts, payload validation and direct-write restrictions passed.');
